"""
v2.1 Phase 6 -- the final measurements on the frozen generator, each stage its own files (rule 14), every output under
Phase-6 names (the Phase-4 lesson: an earlier chain overwrote another phase's files).

    python -m tools.phase6.e6_after_state --stages checklist,audit,holdout,hashes,freeze [--workers 24] [--seeds 500]

  checklist  the Section-9 checklist at the REGISTERED n (PREREG_PHASE_6.md 5.3: 500 seeds per scenario, SCL design,
             seeds from 40000, T = 200) under the v2 criteria (A, `run_checklist`, unchanged) AND the reference criteria
             (B and C, `run_checklist_reference`), with E6.8's rows and item 9's re-stated rule
             -> e6_after_checklist.{md,csv} (A), e6_after_checklist_reference.{md,csv,_items.csv} (B/C)
             plus T in {800, 2000} descriptive rows for items 4 and 9 at 100 flat seeds -> e6_after_checklist_long.{json,md}
  audit      evaluation.leakage_audit.run_audit on the 1,600-path SEP panel, level-free control, no subsampling, n/m as
             cap + indicator, gates="derived" (the derived L1/L2/L2b verdicts read from the criteria file)
             -> e6_after/audit_after_derived.{md,pkl,_L1.csv,_L2.csv,_L4.csv,_checklist_rows.csv}
  holdout    the held-out-scenario split (weakness 67) on the same panel -> e6_after/holdout.{csv,md}
  hashes     the 95-configuration path hashes -> path_hashes_phase6_after.json, compared with the Phase-5 fixture
             (nothing in Phase 6 changes the generator: the comparison must be empty)
  freeze     the manifest rewrite (a logged decision)

The panel must exist (`_panels/sep_phase5_after.pkl`, regenerated by tools.phase5.e5_after_state --stages panel on a
machine that has reproduced the reference rows); the criteria file must carry the gates for the audit's derived verdicts.
"""
